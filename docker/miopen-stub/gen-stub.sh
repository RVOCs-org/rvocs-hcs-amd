#!/usr/bin/env bash
# Regenerate libMIOpen.so.1 from every miopen* symbol the USE_MIOPEN=0 torch
# shared libraries still reference. Usage: gen-stub.sh <torch/lib dir or .so...> [out.so]
# Rationale: the stub set must follow the torch binaries, otherwise import fails with
#   ImportError: libtorch_hip.so: undefined symbol: miopenCreateTensorDescriptor
#   ImportError: libtorch_python.so: undefined symbol: miopenGetVersion
set -euo pipefail
OUT=/tmp/libMIOpen.so.1; SRCS=()
for a in "$@"; do
  if [ -d "$a" ]; then OUT="${OUT_OVERRIDE:-$OUT}"; SRCS+=("$a"/*.so); else SRCS+=("$a"); fi
done
[ "${#SRCS[@]}" -gt 0 ] || { echo "usage: gen-stub.sh <dir|so>..." >&2; exit 1; }
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
: > "$W/syms"
for so in "${SRCS[@]}"; do
  [ -f "$so" ] || continue
  nm -D --undefined-only "$so" 2>/dev/null | awk '{print $NF}' | sed 's/@.*//' | grep -E 'miopen' >> "$W/syms" || true
done
sort -u -o "$W/syms" "$W/syms"
n=$(wc -l < "$W/syms"); [ "$n" -gt 0 ] || { echo "no miopen symbols found" >&2; exit 1; }
{ echo '/* generated by docker/miopen-stub/gen-stub.sh -- do not edit */'
  i=0
  while read -r s; do
    i=$((i+1))
    printf 'long mio_stub_%s(void) __asm__("%s");\nlong mio_stub_%s(void) { return 0; }\n' "$i" "$s" "$i"
  done < "$W/syms"; } > "$W/stub.c"
gcc -shared -fPIC -O1 -Wl,-soname,libMIOpen.so.1 -o "$OUT" "$W/stub.c"
nm -D --defined-only "$OUT" | awk '{print $NF}' | sed 's/@.*//' | sort -u > "$W/def"
missing=$(comm -23 "$W/syms" "$W/def" | wc -l)
echo "needed=$n exported=$(wc -l < "$W/def") missing=$missing size=$(stat -c%s "$OUT")"
[ "$missing" -eq 0 ]
