#!/usr/bin/env bash
# Stage 2: workspace preparation + patch import
#   - verify the source workspace matches the current baseline (submodule pin)
#   - apply patches in patches/<arch>/<component>/series order (idempotent, re-runnable)
#   - generate work/env.sh so later stages and manual debugging can simply source it
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"

if [ "$MODE" = prebuilt ]; then
  log "prebuilt mode has no workspace/patch stage, skipping"
  exit 0
fi

[ -d "$SRC_TREE/build_tools" ] || die "sources not ready: $SRC_TREE (run --stage fetch first)"

pin=$(therock_pin_commit)
head=$(therock_head)
if [ -n "$pin" ] && [ -n "$head" ] && [ "$pin" != "$head" ]; then
  warn "source HEAD(${head:0:12}) does not match the repository pin(${pin:0:12})"
  warn "suggested: git -C upstream/therock checkout $pin && git -C upstream/therock submodule update --init --recursive"
  warn "(or run scripts/tools/baseline.sh restore to return to the pinned state)"
fi

# Align submodules with the pins recorded in the TheRock index (fetch_sources.py
# may leave individual submodules on newer commits, in which case the patch
# baselines would be wrong)
if [ -e "$SRC_TREE/.git" ]; then
  # Note: grep -c exits 1 when the count is 0, which under set -e would fail the
  # assignment, hence the || true
  drift=$(git -C "$SRC_TREE" submodule status 2>/dev/null | grep -c '^+' || true)
  if [ "${drift:-0}" -gt 0 ]; then
    warn "$drift submodule(s) drifted from the indexed pin, realigning first"
    if run git -C "$SRC_TREE" submodule update --init --recursive; then
      # realigning resets the submodule work trees, so the previous "applied" stamps are void
      clear_patch_state
    else
      warn "submodule realignment failed (network?), continuing with patch application"
    fi
  fi
fi

if [ -f "$BASELINE_STAMP" ]; then
  old_pin=$(sed -n 's/^therock=//p' "$BASELINE_STAMP" | head -1)
  old_hash=$(sed -n 's/^patch_series=//p' "$BASELINE_STAMP" | head -1)
  [ "$old_pin" = "$pin" ] || warn "baseline changed: ${old_pin:0:12} -> ${pin:0:12}, patches may need fixes"
  [ "$old_hash" = "$(patch_series_hash)" ] || log "patch series changed, re-checking application state"
fi

# ---------------------------------------------------------------------------
# Apply patches
# ---------------------------------------------------------------------------
if is_porting_branch; then
  if apply_patch_series --strict; then
    log "patch series ready"
  else
    die "patch application failed. How to diagnose:
   scripts/tools/patch.sh check --verbose    # explain conflicts patch by patch
   scripts/tools/patch.sh refresh <comp>/<name>  # rebuild that patch after baseline drift
   see docs/PATCHES.md"
  fi
else
  log "master branch has no porting layer, skipping patches (sources stay as upstream)"
fi

# ---------------------------------------------------------------------------
# Generate env.sh (shared by later stages and manual debugging)
# ---------------------------------------------------------------------------
cat > "$WORK_DIR/env.sh" <<EOF
# generated by scripts/02-workdir.sh, do not edit
export REPO_ROOT="$REPO_ROOT"
export SRC_TREE="$SRC_TREE"
export THEROCK_BUILD="$THEROCK_BUILD"
export DIST_DIR="$DIST_DIR"
export ARCH="$ARCH"
export GPU_ID="$GPU_ID"
export GPU_FAMILY="$GPU_FAMILY"
export GPU_TARGET="$GPU_TARGET"
export ROCM_VERSION="$ROCM_VERSION"
export PATH="\$SRC_TREE/build/bin:\$SRC_TREE/build/dist/rocm/bin:\$PATH"
EOF
log "environment file: $WORK_DIR/env.sh (usage: source $WORK_DIR/env.sh)"

# ---------------------------------------------------------------------------
# Record the baseline stamp
# ---------------------------------------------------------------------------
if [ "$DRY_RUN" != 1 ]; then
  baseline_stamp > "$BASELINE_STAMP"
fi

# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------
if is_porting_branch; then
  echo "---- patch status ----"
  for comp in $(patch_components); do
    files=$(series_files "$comp")
    if [ -z "$files" ]; then printf '  %-20s (no patches)\n' "$comp"; continue; fi
    n=$(printf '%s\n' "$files" | wc -l)
    case "$(series_state "$comp")" in
      applied) printf '  %-20s %d/%d applied\n' "$comp" "$n" "$n" ;;
      pending) printf '  %-20s 0/%d pending (not applied)\n' "$comp" "$n" ;;
      missing) printf '  %-20s %d (sources not ready)\n' "$comp" "$n" ;;
      *)       printf '  %-20s %d (partially applied, needs review)\n' "$comp" "$n" ;;
    esac
  done
fi

log "workdir done: editable sources are in $SRC_TREE"
