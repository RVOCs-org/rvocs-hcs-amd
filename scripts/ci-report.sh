#!/usr/bin/env bash
# Build an HTML CI report for the current run and email it.
# env: GITHUB_RUN_ID REPO_SLUG MAIL_ENV(/home/ubuntu/.config/rvocs/mail.env)
set -uo pipefail
ROOT=/home/ubuntu/RVOCs-CICD/rvocs-hcs-amd
OUTD="$ROOT/artifacts/reports"; mkdir -p "$OUTD"
RID="${GITHUB_RUN_ID:-$(date +%s)}"; REPO="${REPO_SLUG:-RVOCs-org/rvocs-hcs-amd}"
OUT="$OUTD/ci-report-$RID.html"
python3 - "$RID" "$REPO" "$ROOT" "$OUT" <<'PY'
import json,sys,urllib.request,html,os,glob,datetime
rid,repo,root,out=sys.argv[1:5]
def api(p):
    r=urllib.request.Request(f"https://api.github.com/repos/{repo}{p}",headers={"User-Agent":"ci-report"})
    return json.loads(urllib.request.urlopen(r,timeout=30).read())
run=api(f"/actions/runs/{rid}"); jobs=api(f"/actions/runs/{rid}/jobs")["jobs"]
def dur(j):
    if not (j.get("started_at") and j.get("completed_at")): return "-"
    f=lambda s: datetime.datetime.strptime(s,"%Y-%m-%dT%H:%M:%SZ")
    return "%ds"%int((f(j["completed_at"])-f(j["started_at"])).total_seconds())
rows=[]
for j in jobs:
    steps="".join(f"<li>{html.escape(s['name'])}: <b>{s['conclusion'] or s['status']}</b></li>" for s in j.get("steps",[]))
    rows.append(f"<tr><td>{html.escape(j['name'])}</td><td>{j['status']}</td><td><b>{j.get('conclusion') or '-'}</b></td><td>{dur(j)}</td><td><details><summary>steps</summary><ul>{steps}</ul></details></td></tr>")
stages=""
for f in sorted(glob.glob(f"{root}/artifacts/{rid}-*/**/ci-summary.json",recursive=True)):
    for line in open(f):
        try: d=json.loads(line)
        except Exception: continue
        stages+=f"<tr><td>{d.get('stage')}</td><td>{d.get('key')}</td><td>{d.get('duration_s')}s</td><td>rc={d.get('rc')}</td><td>{html.escape(str(d.get('tag','')))}</td></tr>"
mv=""
for f in sorted(glob.glob(f"{root}/artifacts/model-verify/*.json"))[-1:]:
    d=json.load(open(f)); p=d.get("perf",{}); 
    mv=f"<p>model={d.get('model')} startup={d.get('startup_s')}s seq_avg={p.get('sequential_latency_s')} tps_stream={p.get('sequential_tps')} c4_throughput={p.get('c4_throughput_tps')} tok/s</p>"
color="#1a7f37" if run.get("conclusion")=="success" else "#cf222e"
html_doc=f"""<html><body style="font-family:system-ui,Segoe UI,Arial">
<h2 style="color:{color}">CI {html.escape(run.get('name',''))} — {run.get('conclusion') or run.get('status')}</h2>
<p>run <a href="{run.get('html_url')}">{rid}</a> · ref <b>{html.escape(run.get('head_branch') or '')}</b> · commit {run.get('head_sha','')[:12]} · event {run.get('event')} · {run.get('created_at')}</p>
<h3>Jobs</h3><table border="1" cellpadding="6" cellspacing="0" style="border-collapse:collapse;font-size:13px">
<tr><th>job</th><th>status</th><th>result</th><th>duration</th><th>steps</th></tr>{''.join(rows)}</table>
<h3>Stages</h3><table border="1" cellpadding="6" cellspacing="0" style="border-collapse:collapse;font-size:13px">
<tr><th>stage</th><th>key</th><th>duration</th><th>rc</th><th>image tag</th></tr>{stages or '<tr><td colspan=5>(no ci-summary.json)</td></tr>'}</table>
<h3>Model verify</h3>{mv or '<p>(no model-verify json)</p>'}
<p style="color:#666;font-size:12px">generated by scripts/ci-report.sh</p></body></html>"""
open(out,"w",encoding="utf-8").write(html_doc); print("report:",out)
PY
MAIL_ENV="${MAIL_ENV:-/home/ubuntu/.config/rvocs/mail.env}"
[ -f "$MAIL_ENV" ] || { echo "[report] no $MAIL_ENV -> report written only: $OUT"; exit 0; }
set -a; . "$MAIL_ENV"; set +a
python3 - "$OUT" <<'PY'
import os,smtplib,sys,email.message,email.utils
h=email.message.EmailMessage()
h["Subject"]=os.environ.get("MAIL_SUBJECT","RVOCs CI report")
h["From"]=os.environ["MAIL_FROM"]; h["To"]=os.environ["MAIL_TO"]
h.set_content("CI report attached (HTML).")
h.add_attachment(open(sys.argv[1],"rb").read(),maintype="text",subtype="html",filename=os.path.basename(sys.argv[1]))
cls=smtplib.SMTP_SSL if os.environ.get("SMTP_SSL","1")=="1" else smtplib.SMTP
with cls(os.environ["SMTP_HOST"],int(os.environ.get("SMTP_PORT","465"))) as s:
    s.login(os.environ["SMTP_USER"],os.environ["SMTP_PASS"]); s.send_message(h)
print("[report] mailed to",os.environ["MAIL_TO"])
PY